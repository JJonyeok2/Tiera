import type { Category, ScoreScope, ToolAxis } from "@/db/schema";

/**
 * 베이지안 신뢰 임계값 m.
 * 리뷰 3개짜리 신규 모델이 평균 5.0으로 1위를 먹는 사고를 막는다.
 * 값이 클수록 신규 모델이 전체 평균 쪽으로 강하게 끌려간다.
 * 트래픽이 붙으면 상향할 것.
 */
export const CONFIDENCE_M = 30;

/**
 * 종합 점수 산출 가중치.
 * 개발자 타깃이라 코딩·추론에 무게를 뒀다. SPEC 13절 #4.
 * 평가 수가 0인 카테고리는 분모·분자에서 제외되므로 합이 1일 필요는 없다.
 */
export const CATEGORY_WEIGHT: Record<Category, number> = {
  CODING: 0.3,
  REASONING: 0.3,
  WRITING: 0.2,
  MULTIMODAL: 0.2,
};

export const CATEGORIES: Category[] = ["CODING", "WRITING", "REASONING", "MULTIMODAL"];

export const SCOPES: ScoreScope[] = ["OVERALL", ...CATEGORIES];

/** 5점 척도 → 100점 환산. 1점=20, 5점=100. SPEC 13절 #2. */
export const RATING_MIN = 1;
export const RATING_MAX = 5;

/** 벤치마크 min-max 정규화는 표본이 이 수 미만이면 신뢰할 수 없어 제외한다. */
export const MIN_MODELS_FOR_NORMALIZATION = 3;

/**
 * 벤치마크 정규화의 하한.
 *
 * min-max를 0~100으로 펴면 최하위 모델이 항상 0점이 된다. 반면 커뮤니티 점수는
 * 5점 척도를 환산한 것이라 바닥이 20점이다. 두 점수를 나란히 놓고 비교하는 것이
 * 이 서비스의 핵심인데, 축의 바닥이 다르면 비교 자체가 성립하지 않는다.
 * 그래서 벤치마크도 같은 20~100 밴드에 올린다.
 */
export const BENCH_FLOOR = 20;

/**
 * 괴리 판정 기준 = "순위 차이".
 *
 * 점수 차이로 판정하지 않는 이유: 벤치마크 점수는 min-max라 본질적으로 상대 순위이고
 * 커뮤니티 점수는 절대 평점이다. 둘의 점수 차를 빼면 "실제로 평가가 엇갈렸다"가 아니라
 * "두 척도의 분포가 다르다"를 재게 된다. 순위 차이는 척도에 무관하고,
 * "벤치마크 3위인데 커뮤니티 9위"라고 그대로 보여줄 수 있어 설명하기도 쉽다.
 */
export const GAP_RANK_THRESHOLD = 3;

// --- 도구 (SPEC 23.6) -------------------------------------------------------

export const TOOL_AXES: ToolAxis[] = ["EASE", "OUTPUT", "PRICE", "KOREAN"];

/**
 * 도구 4축 가중치 — **의도적으로 전부 같다.**
 *
 * 모델 쪽 CATEGORY_WEIGHT는 "개발자 타깃이라 코딩·추론에 무게를 둔다"는 근거가
 * 있었다. 도구에는 그런 근거가 없다. "결과물이 가격보다 1.5배 중요하다" 같은 건
 * 내가 정할 일이 아니라 사용자가 판단할 일이고, 4축 점수는 어차피 따로 보여준다.
 *
 * 근거 없는 가중치는 편집자의 취향을 종합 점수에 몰래 섞는 것이다.
 * 실제 후기가 쌓여 축 간 상관을 볼 수 있게 되면 그때 근거를 갖고 조정한다.
 */
export const TOOL_AXIS_WEIGHT: Record<ToolAxis, number> = {
  EASE: 0.25,
  OUTPUT: 0.25,
  PRICE: 0.25,
  KOREAN: 0.25,
};

/**
 * 도구용 베이지안 신뢰 임계값.
 *
 * 모델(30)보다 낮다. 이유 두 가지:
 *   1. 도구는 40여 개고 모델은 300개가 넘는다. 같은 m이면 도구 쪽은 점수가 전부 전체 평균에
 *      붙어버려서, 후기가 한참 쌓일 때까지 순위가 아무것도 구분하지 못한다.
 *   2. 축이 더 단순하다. "이거 쓰기 쉬웠나"는 "코딩 능력이 어떤가"보다 사람마다
 *      덜 갈린다. 표본이 적어도 평균이 빨리 안정된다.
 *
 * 그래도 0은 아니다 — 후기 3개짜리가 평균 5.0으로 1위를 먹는 건 여전히 막아야 한다.
 * 트래픽이 붙으면 상향할 것.
 */
export const TOOL_CONFIDENCE_M = 10;

/**
 * 티어 배지를 띄우기 시작하는 최소 후기 수.
 *
 * 베이지안 보정만으로는 부족하다. 보정은 "전체 평균 C 쪽으로 당긴다"는 건데,
 * 후기가 사이트 전체에 몇 개뿐이면 **C 자체가 그 몇 개로 만들어진다.**
 * 실제로 후기 1개를 넣어보니 보정 후 점수가 원점수와 똑같이 나왔다 —
 * 그 한 명이 전체 평균이기 때문이다. 수식은 맞는데 결과가 의미가 없다.
 *
 * 그 상태로 별과 티어를 띄우면 비전문가는 "이 도구는 실버 등급"으로 읽는다.
 * 실제로는 "한 사람이 그렇게 말했다"인데도. 숫자를 숨기는 게 아니라
 * **단정하는 표시를 미루는 것**이다 — 후기 수는 그대로 보여준다.
 */
export const TOOL_MIN_REVIEWS_FOR_TIER = 3;
